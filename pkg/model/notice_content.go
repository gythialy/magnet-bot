package model

import "time"

// NoticeContent caches one notice's sanitized full text, keyed by its URL.
//
// A notice is delivered to at most one history row per user, but the body is
// the same for everyone, so the cache is keyed by URL alone and shared: the
// second reader of a notice costs one row read instead of a page fetch.
//
// The stored HTML has already passed utils.ExtractNoticeBody /
// utils.SanitizeNoticeFragment, so whatever writes here is safe to insert into
// the Mini App document. Sanitizing on write (not on read) is what keeps a
// stored body honest: no request path can resurrect markup that was dropped.
type NoticeContent struct {
	URL       string    `gorm:"column:url;primaryKey;size:512" json:"url"`
	HTML      string    `gorm:"column:html;not null" json:"html"`
	FetchedAt time.Time `gorm:"column:fetched_at;not null" json:"fetchedAt"`
}

// TableName is explicit because this model is not generated by gorm/gen.
func (NoticeContent) TableName() string { return "notice_contents" }
