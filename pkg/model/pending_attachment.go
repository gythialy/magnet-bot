package model

import "time"

// PendingAttachment is a notice whose PDF attachment could not be delivered.
//
// The text message already reached the user, so a failed attachment is not
// rolled back: it is queued here and retried in the background. (user_id, url)
// is the primary key, so a notice has at most one pending attachment per user;
// importing the same notice again refreshes the existing row instead of
// queueing a duplicate.
type PendingAttachment struct {
	UserID     int64  `gorm:"column:user_id;primaryKey;autoIncrement:false"`
	URL        string `gorm:"column:url;primaryKey;size:512"`
	ReplyTo    int    `gorm:"column:reply_to;not null;default:0"`
	Title      string `gorm:"column:title;not null"`
	TenderCode string `gorm:"column:tender_code"`
	// Attempts counts the failed deliveries of this row. The retrier gives up
	// once it reaches the configured maximum.
	Attempts int `gorm:"column:attempts;not null;default:0"`
	// NextAttemptAt is when the row becomes due again.
	NextAttemptAt time.Time `gorm:"column:next_attempt_at;not null;index"`
	// LockedUntil is a short lease that keeps two bot instances sharing one
	// database from sending the same attachment twice.
	LockedUntil time.Time `gorm:"column:locked_until"`
	LastError   string    `gorm:"column:last_error"`
	CreatedAt   time.Time `gorm:"column:created_at;not null"`
}

// TableName is explicit because this model is not generated by gorm/gen.
func (PendingAttachment) TableName() string { return "pending_attachments" }
