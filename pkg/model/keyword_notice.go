package model

import "time"

// KeywordNotice records that a keyword matched a notice.
//
// The (keyword_id, url) pair is the primary key, so recording the same match
// again is a no-op: re-crawling a window can never inflate a keyword's notice
// count. The rows are only a dedupe log and are pruned after the retention
// window.
type KeywordNotice struct {
	KeywordID int32     `gorm:"column:keyword_id;primaryKey;autoIncrement:false"`
	URL       string    `gorm:"column:url;primaryKey;size:512"`
	CreatedAt time.Time `gorm:"column:created_at;not null"`
}

// TableName is explicit because this model is not generated by gorm/gen.
func (KeywordNotice) TableName() string { return "keyword_notices" }
